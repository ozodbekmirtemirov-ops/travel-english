const fm = FileManager.local();
const PATH = fm.joinPath(fm.documentsDirectory(), "travel-english-mode.json");
function getMode() { try { return JSON.parse(fm.readString(PATH)) || { on: false }; } catch (e) { return { on: false }; } }
function setMode(on) { const m = { on: on, since: on ? Date.now() : null }; fm.writeString(PATH, JSON.stringify(m)); return m; }

// Same formula as in the TRAVEL ENGLISH app, so the word matches everywhere.
function hourIndex(d) { return Math.floor((d.getTime() / 60000 - d.getTimezoneOffset()) / 60); }
function wordAt(d) { const n = WORDS.length; return WORDS[((hourIndex(d) * 73) % n + n) % n]; }
function nextHour() { const d = new Date(); d.setMinutes(0, 0, 0); d.setHours(d.getHours() + 1); return d; }
function hhmm(d) { return ("0" + d.getHours()).slice(-2) + ":00"; }
function tripDay(m) { return m.since ? Math.floor((Date.now() - m.since) / 86400000) + 1 : 1; }

const params = args.queryParameters || {};
if (params.mode === "on") setMode(true);
if (params.mode === "off") setMode(false);
let mode = getMode();

function text(stack, value, font, color, lines, scale) {
  const t = stack.addText(value);
  t.font = font;
  if (color) t.textColor = color;
  if (lines) t.lineLimit = lines;
  t.minimumScaleFactor = scale || 0.6;
  return t;
}

function buildWidget(family) {
  const w = new ListWidget();
  w.refreshAfterDate = nextHour();
  w.url = URLScheme.forRunningScript();
  const word = wordAt(new Date());
  const [en, ru, meaning, emoji] = word;

  // ---------- Lock screen ----------
  if (family === "accessoryInline") {
    w.addText(mode.on ? emoji + " " + en + " — " + ru : "🏠 Travel English · выкл.");
    return w;
  }
  if (family === "accessoryCircular") {
    w.addAccessoryWidgetBackground = true;
    const s = w.addStack(); s.layoutVertically(); s.centerAlignContent();
    if (mode.on) { text(s, emoji, Font.systemFont(20), null, 1); text(s, en, Font.boldSystemFont(11), null, 1, 0.5); }
    else { text(s, "🏠", Font.systemFont(22), null, 1); text(s, "выкл.", Font.mediumSystemFont(10), null, 1); }
    return w;
  }
  if (family === "accessoryRectangular") {
    if (!mode.on) {
      text(w, "🏠 TRAVEL ENGLISH", Font.boldSystemFont(13), null, 1);
      text(w, "Режим путешествия выключен", Font.systemFont(12), null, 1);
      text(w, "Нажмите → ✈️ Я улетел", Font.mediumSystemFont(12), null, 1);
      return w;
    }
    text(w, emoji + " " + en.toUpperCase(), Font.heavySystemFont(16), null, 1, 0.55);
    text(w, ru, Font.semiboldSystemFont(14), null, 1, 0.6);
    text(w, meaning, Font.systemFont(12), null, 1, 0.55);
    return w;
  }

  // ---------- Home screen (small / medium / large) ----------
  const g = new LinearGradient();
  g.colors = [new Color("#1d1d1f"), new Color("#0f2a1c")];
  g.locations = [0, 1];
  w.backgroundGradient = g;
  w.setPadding(14, 16, 14, 16);
  const green = new Color("#3ccf82"), white = Color.white(), grey = new Color("#a1a1a8");
  const big = family === "medium" || family === "large";

  const head = w.addStack(); head.centerAlignContent();
  text(head, "✈️ WORD OF THE HOUR", Font.heavySystemFont(10), green, 1);
  head.addSpacer();
  if (mode.on && big) text(head, "День " + tripDay(mode), Font.boldSystemFont(10), grey, 1);
  w.addSpacer(big ? 8 : 6);

  if (!mode.on) {
    text(w, "🏠", Font.systemFont(30), null, 1);
    w.addSpacer(4);
    text(w, "Режим путешествия выключен", Font.boldSystemFont(14), white, 2);
    w.addSpacer(2);
    text(w, "Нажмите, чтобы включить ✈️", Font.systemFont(12), grey, 2);
    w.addSpacer();
    return w;
  }

  const row = w.addStack(); row.centerAlignContent();
  text(row, emoji, Font.systemFont(big ? 34 : 26), null, 1);
  row.addSpacer(8);
  text(row, en, Font.heavySystemFont(big ? 30 : 22), white, 1, 0.5);
  w.addSpacer(4);
  text(w, ru, Font.semiboldSystemFont(big ? 18 : 15), green, 1);
  w.addSpacer(2);
  text(w, meaning, Font.systemFont(big ? 14 : 12), grey, 2);
  w.addSpacer();
  text(w, "Новое слово в " + hhmm(nextHour()), Font.mediumSystemFont(10), grey, 1);
  return w;
}

if (config.runsInWidget) {
  Script.setWidget(buildWidget(config.widgetFamily));
} else if (params.mode) {
  // Opened from the TRAVEL ENGLISH app button: just switch and return.
  Script.complete();
} else {
  const a = new Alert();
  a.title = "✈️ TRAVEL ENGLISH";
  a.message = mode.on
    ? "Режим путешествия включён (день " + tripDay(mode) + "). Каждый час на экране блокировки — новое слово."
    : "Режим путешествия выключен. Включите его, и каждый час будет появляться новое слово.";
  a.addAction(mode.on ? "🏠 Я прилетел обратно" : "✈️ Я улетел");
  a.addAction("👀 Слово этого часа");
  a.addCancelAction("Закрыть");
  const r = await a.presentSheet();
  if (r === 0) mode = setMode(!mode.on);
  if (r === 1) {
    const [en, ru, meaning, emoji] = wordAt(new Date());
    const b = new Alert();
    b.title = emoji + " " + en;
    b.message = ru + "\n" + meaning + "\n\nСледующее слово в " + hhmm(nextHour());
    b.addAction("🔊 Произнести");
    b.addCancelAction("OK");
    if ((await b.presentAlert()) === 0) Speech.speak(en);
  }
  if (r === 0) await buildWidget("medium").presentMedium();
  Script.complete();
}
